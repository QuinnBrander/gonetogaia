/**
 * Tide Board calibration + spawn rendering helpers.
 *
 * The Tide board art (`/board/tide.jpg`) has the 5x5 grid printed inside it
 * with cyan-outlined cells. Tokens (delver / boss / minion) are rendered as
 * absolutely-positioned DOM elements over the image, using percentage-based
 * coordinates so the whole layout scales with the container.
 *
 * The constants below are calibrated by eye against `tide.jpg`. If the art
 * changes, retune `GRID_INSET_PCT` and `GRID_SIZE_PCT` and re-check by
 * toggling `?debugGrid=1` to draw the calibration lines on top of the board.
 */

import type { EncounterState, EnemyFacing } from "../state";
import { HEROES, getEnemy } from "../data";
import { getFatalFlawTier, isFatalFlawProtected } from "../engine/encounter";
import tideTiles from "../../data/tideTiles.json";

/**
 * Per-cell tile coordinates measured directly from the printed board art.
 *
 * `data/tideTiles.json` is generated by
 * `tools/pdf-extract/detect_tiles_from_annotation.mjs`, which reads a
 * user-painted screenshot of /board/tide.jpg with solid teal squares
 * over each visible tile rim, and emits the centre + size of each square
 * as a percentage of the board image. Re-run that tool whenever the board
 * art changes.
 *
 * The data is a 5x5 array indexed `cells[row][col]`. Each entry has
 * `cxPct, cyPct` (centre %) and `wPct, hPct` (rim size %).
 *
 * MANUAL TOUCH-UPS: the auto-detect tool currently mis-measures one
 * cell because the source annotation has a stray paint blob:
 *   - cell (col=1, row=2): `x0` was 184 / `wPct` was 18.222 — extending
 *     ~20px too far west. Manually corrected to match the column-1
 *     siblings (`x0=204`, `wPct=15.889`).
 * If you regen the JSON, re-apply that fix (or fix the source
 * annotation PNG and re-run the tool).
 */
type CellRect = { cxPct: number; cyPct: number; wPct: number; hPct: number };
const CELLS = tideTiles.cells as CellRect[][];

/**
 * Average cell PITCH (centre-to-centre distance) in percent. Useful when
 * something needs a single representative cell-size number — e.g. sizing
 * delver chips that aren't bound to any one tile. Computed once at module
 * load from the measured grid.
 */
export const CELL_SIZE_PCT = (() => {
  // Mean of horizontal pitches in row 2 + vertical pitches in col 2.
  let total = 0, n = 0;
  for (let c = 0; c < 4; c++) {
    total += CELLS[2]![c + 1]!.cxPct - CELLS[2]![c]!.cxPct; n++;
  }
  for (let r = 0; r < 4; r++) {
    total += CELLS[r + 1]![2]!.cyPct - CELLS[r]![2]!.cyPct; n++;
  }
  return total / n;
})();

/**
 * Vertical-only centred-shrink factor applied to every cell's
 * `cyPct` before it's handed to the renderer. The raw calibration
 * came from a 900x900 source whose row span is slightly wider than
 * the printed row span on the live `tide.jpg` (1024x1024) — the
 * symptom was that row 0 cards rode above the printed top-row rim
 * and row 4 cards rode below the bottom-row rim (user report
 * 2026-05-19). Cell SIZES still match the printed rims, so this
 * correction touches POSITIONS only (`cellCenterPct` /
 * `cellOriginPct`), leaving `cellSizePct` + `CELL_SIZE_PCT`
 * untouched.
 *
 * Tuning history (with the symptom each setting addresses):
 *   - `1.00` (original) — top cards rode ABOVE the top rim, bottom
 *     cards rode BELOW the bottom rim.
 *   - `0.96` (2026-05-19) — over-corrected: top cards now sat too
 *     far INSIDE the top rim, bottom cards too far inside the
 *     bottom rim (user report 2026-05-20 with Q2W1 screenshot).
 *   - `0.985` (current, 2026-05-20) — splits the difference; top
 *     row nudges back UP and bottom row nudges back DOWN by ~half
 *     of the previous correction. Re-tune if the board art changes
 *     or the calibration tool is re-run against the current image.
 *
 * Centred shrink toward 50% — the centre row is unchanged and the
 * nudge grows linearly toward the outer rows. At the current
 * 0.985 factor:
 *
 *   row 0 (cy 11.28 → 11.86): nudged DOWN by ~0.58%
 *   row 1 (cy 30.56 → 30.85): nudged DOWN by ~0.29%
 *   row 2 (cy 49.94 → ~50.0): unchanged (centre)
 *   row 3 (cy 69.33 → 69.04): nudged UP   by ~0.29%
 *   row 4 (cy 88.67 → 88.09): nudged UP   by ~0.58%
 *
 * `1.0` would disable the correction. Smaller values shrink more
 * aggressively. Horizontal axis (`cxPct`) is intentionally left
 * untouched — the column span lined up with the printed rim
 * columns once the size shrink was reverted, so only the vertical
 * span needs the nudge.
 */
const ROW_POSITION_SHRINK_FACTOR = 0.985;

/** Pull a vertical-axis percentage toward the 50% midpoint by
 *  `ROW_POSITION_SHRINK_FACTOR`. 50 maps to 50 (centre row
 *  unchanged); top/bottom rows move toward centre symmetrically. */
function shrinkRowPct(cyPct: number): number {
  return 50 + (cyPct - 50) * ROW_POSITION_SHRINK_FACTOR;
}

/**
 * Centre of grid cell (col,row), expressed as percentage of the board image
 * (origin top-left). Quest #1 uses (x=col, y=row) where (0,0) is north-west.
 *
 * The vertical centre is post-corrected by `shrinkRowPct` (see the
 * doc block above) so outer rows nudge toward the board centre and
 * the rendered grid lines up with the printed row rims on
 * `tide.jpg`. Horizontal centre is the raw calibration value.
 */
export function cellCenterPct(col: number, row: number): { left: number; top: number } {
  const cell = CELLS[row]?.[col];
  if (!cell) throw new Error(`No tide tile data for (col=${col}, row=${row})`);
  return { left: cell.cxPct, top: shrinkRowPct(cell.cyPct) };
}

/** Top-left corner of grid cell (col,row), as percentages. Vertical
 *  axis uses the corrected `cyPct` (same as `cellCenterPct`) so the
 *  derived corner still matches `centre - size/2`. */
export function cellOriginPct(col: number, row: number): { left: number; top: number } {
  const cell = CELLS[row]?.[col];
  if (!cell) throw new Error(`No tide tile data for (col=${col}, row=${row})`);
  return {
    left: cell.cxPct - cell.wPct / 2,
    top: shrinkRowPct(cell.cyPct) - cell.hPct / 2,
  };
}

/**
 * Visible rim size of grid cell (col,row), as percentages. Use this to size
 * elements that should fit *inside* the printed tile rim (enemy card art),
 * rather than CELL_SIZE_PCT (the centre-to-centre pitch, which includes the
 * inter-tile gap).
 */
export function cellSizePct(col: number, row: number): { wPct: number; hPct: number } {
  const cell = CELLS[row]?.[col];
  if (!cell) throw new Error(`No tide tile data for (col=${col}, row=${row})`);
  return { wPct: cell.wPct, hPct: cell.hPct };
}

/** A token to render on the board. */
export interface BoardToken {
  /** Internal id used for click/hover lookups. */
  id: string;
  /**
   * Token category. New kinds need a render branch in every
   * `renderTokens*` consumer (today: BoardScreen, WavePhases,
   * DelverSpawnPick).
   *
   *   `delver`          — a hero chip at the delver's current tile.
   *   `witness`         — the Q2+ Witness companion robot. Renders
   *                       as a copper-tinted "Witness" chip the same size
   *                       as a delver token. Non-interactive once
   *                       the wave starts (no turn, no HP, no
   *                       combat) — DelverSpawnPick gives it the
   *                       same tap-to-reposition affordance as a
   *                       delver during the pick phase only.
   *   `boss` / `minion` — printed enemy card art at the enemy tile.
   *   `drop`            — monster-part pickup waiting to be collected
   *                       (per-delver `TileDrop`).
   *   `memory-fragment` — Memory Fragment glyph from the drawn
   *                       Spawn Card's `memoryFragments[]`. Visible
   *                       but non-interactive today; pickup wiring
   *                       lands in a later slice that drains
   *                       `encounter.memoryFragments` and bumps
   *                       `state.memoryChips`.
   */
  kind: "delver" | "witness" | "boss" | "minion" | "drop" | "memory-fragment" | "friendly-encounter" | "rebirth";
  /** Grid column 0..4. */
  col: number;
  /** Grid row 0..4 (0 = north). */
  row: number;
  /** Short label drawn inside the token. */
  label: string;
  /** Full descriptive name (used in info panel/tooltip). */
  name: string;
  /** Enemy/hero card id this token represents (if any). */
  cardId?: string;
  /** Enemy live HP (clamped to [0, maxHp]). Populated for `boss`/`minion`
   *  tokens only. The renderer paints a red-heart overlay on top of the
   *  card art's printed max-HP widget whenever `currentHp < maxHp` (and
   *  shows 0 during the deferred-kill counter window). */
  currentHp?: number;
  /** Enemy printed max HP. Populated for `boss`/`minion` tokens only. */
  maxHp?: number;
  /** Quarter-turn rotation of the enemy card art on the board, in
   *  degrees CW from the printed orientation. Mutated by the Slip
   *  Strider Boots ONGOING ability. The HP heart overlay rotates
   *  with the card (it's painted inside the same rotated container)
   *  so the rotated number stays anchored to the card's top-right
   *  corner regardless of orientation. */
  facing?: EnemyFacing;
  /** For `kind: "drop"` only — relative URL of the per-suit/per-level
   *  token art under `/tokens/` (e.g. `/tokens/minion-mind.webp`). */
  dropArt?: string;
  /** For `kind: "drop"` only — which delver this drop is owed to.
   *  The renderer can use this to highlight pickups when the matching
   *  delver is the active turn. */
  dropHeroId?: string;
  /** For `kind: "delver"` only — campaign-state hero id (e.g.
   *  `"hero-01"`). Click handlers on the pick screen / future
   *  delver-token interactions need this to map back to a hero
   *  without re-deriving it from `cardId` or `label`. */
  heroId?: string;
  /** For `kind: "boss"` / `"minion"` only — tier on the enemy's
   *  Fatal Flaw ability (rulebook p16; `enemy.abilities[].level`).
   *  `null` when the enemy has no Fatal Flaw (Q1 enemies, future
   *  no-flaw mooks). Drives the small "L1" / "L2" pip painted on
   *  top of the card art so the player can see the tier ladder
   *  at a glance. */
  fatalFlawTier?: number | null;
  /** For `kind: "boss"` / `"minion"` only — true when this enemy
   *  is currently UNKILLABLE because a lower-tier Fatal Flaw
   *  enemy is still alive. Drives the "protected" CSS class +
   *  tooltip so the player understands why their attack pinned
   *  the HP at 1 instead of dropping it to 0. */
  fatalFlawProtected?: boolean;
  /** For `kind: "boss"` / `"minion"` only — monster tokens sitting on the
   *  enemy's card (Guards count, Vicious token, Accurate mark holder).
   *  Rendered as small badges by {@link renderEnemyStatusTokensHtml}. */
  statusTokens?: { label: string; title: string }[];
}

/**
 * Build the full set of board tokens from the LIVE encounter state.
 *
 * Replaces the old `buildWave1Tokens(spawn, assignment)` which read from
 * the static spawn data + a parallel id-assignment array. With Slice 4a,
 * delver positions move and enemies die, so the static spawn data is no
 * longer the source of truth — the encounter is. See DESIGN.md §6.1.
 *
 * Dead enemies are skipped entirely (no ghost tokens left on their tiles).
 */
export function buildEncounterTokens(
  encounter: EncounterState,
): BoardToken[] {
  const tokens: BoardToken[] = [];

  // Delvers — one token per hero at their CURRENT position. Same-tile
  // stacking is handled by the renderer's fan-out (BoardScreen).
  for (const hero of HEROES) {
    const pos = encounter.delverPositions[hero.id];
    if (!pos) continue;
    tokens.push({
      id: `delver-${hero.suit}`,
      kind: "delver",
      col: pos.x,
      row: pos.y,
      label: hero.suit === "mind" ? "Mind" : "Body",
      name: `${hero.suit === "mind" ? "Mind" : "Body"} delver`,
      cardId: `hero-${hero.suit}`,
      heroId: hero.id,
    });
  }

  // Witness companion (Q2+) — single board chip with a "W" label.
  // Lives on `encounter.witnessPosition` (null for Q1). Joins the
  // delver fan-out at the same tile because companion + delvers
  // stack on the spawn-pick compass tile by default; the renderer
  // treats `kind: "delver"` and `kind: "witness"` as a single
  // "humanoid token" family for stacking, so the W chip slots in
  // next to M / B rather than overlapping perfectly.
  if (encounter.witnessPosition) {
    tokens.push({
      id: "witness",
      kind: "witness",
      col: encounter.witnessPosition.x,
      row: encounter.witnessPosition.y,
      label: "Witness",
      name: "Witness (companion)",
    });
  }

  // Enemies — alive only. (`alive` flips to false in `finalizeAttackSession`,
  // i.e. AFTER the shared counter resolves — see DESIGN.md §5.4.2 — so a
  // dying enemy stays in the token list with `currentHp == 0` for the
  // duration of the counter prompt, then disappears with the card.)
  for (const enemy of encounter.enemies) {
    if (!enemy.alive) continue;
    const isBoss = enemy.instanceId === "boss" || !!enemy.linkedTo;
    const cardNum = enemy.cardId.split("-").pop() ?? "?";
    const label = isBoss ? "S" : String(Number(cardNum) || "?");
    const name  = isBoss ? "Soulhunter (boss)" : `Crystanid #${label}`;
    const card = getEnemy(enemy.cardId);
    const maxHp = card.hp;
    const currentHp = Math.max(0, maxHp - enemy.damageTaken);
    const fatalFlawTier = getFatalFlawTier(card);
    // `isFatalFlawProtected` is O(n) per token but n is bounded
    // by 8 (1 boss + 7 minions) for every wave we ship today, so
    // the total cost per render is ~64 ops — well below the noise
    // floor of a DOM repaint. If a future wave bumps the enemy
    // count materially, consider caching the per-tier alive count
    // on the encounter and deriving protection from that.
    const fatalFlawProtected = fatalFlawTier == null
      ? false
      : isFatalFlawProtected(encounter, enemy);
    const statusTokens: { label: string; title: string }[] = [];
    if ((enemy.guardTokens ?? 0) > 0) {
      statusTokens.push({ label: `G${enemy.guardTokens}`, title: `Guards: ${enemy.guardTokens} monster token(s) left. It suffers no damage until they're gone; each attack removes one.` });
    }
    if (enemy.viciousToken) {
      statusTokens.push({ label: "V", title: "Vicious: attacks deal at most 1 damage until an adjacent delver suffers damage." });
    }
    if (enemy.invulnerableToken) {
      statusTokens.push({ label: "I", title: "Invulnerable: the next delver attack deals no damage, then this token is removed." });
    }
    if (enemy.shellToken) {
      statusTokens.push({ label: "S", title: "Shell: invulnerable to damage until one of its counterattacks lands." });
    }
    if (encounter.corruption?.bossInstanceId === enemy.instanceId) {
      const suit = HEROES.find((h) => h.id === encounter.corruption!.heroId)?.suit;
      statusTokens.push({ label: suit === "body" ? "C:B" : "C:M", title: `Corruption: the ${suit === "body" ? "Body" : "Mind"} delver suffers 1 damage at the end of each turn until this boss is killed.` });
    }
    if (encounter.stolenWeapon && card.abilities.some((a) => a.kind === "steals")) {
      statusTokens.push({ label: "W", title: `Steals: holds the ${encounter.stolenWeapon.cardId} card. Kill it, or damage it with a different weapon, to get it back (exhausted).` });
    }
    const markHolder = encounter.accurateMarks[enemy.instanceId];
    if (markHolder) {
      const suit = HEROES.find((h) => h.id === markHolder)?.suit;
      statusTokens.push({ label: suit === "body" ? "A:B" : "A:M", title: `Accurate: its token is on the ${suit === "body" ? "Body" : "Mind"} delver's board. If that delver attacks it, its counterattack always hits.` });
    }
    tokens.push({
      id: enemy.instanceId,
      kind: isBoss ? "boss" : "minion",
      col: enemy.x,
      row: enemy.y,
      label,
      name,
      cardId: enemy.cardId,
      currentHp,
      maxHp,
      facing: enemy.facing,
      fatalFlawTier,
      fatalFlawProtected,
      statusTokens,
    });
  }

  // Tile drops — one BoardToken per `TileDrop` (per-delver per-dropId).
  // Art is suit-keyed for minion-parts and suit-keyed + level-keyed for
  // boss-parts (see `dropArtFor`). The renderer fans these out in a
  // tile corner so multiple drops on the same tile (e.g. one per delver)
  // sit edge-to-edge.
  const HERO_INDEX = new Map(HEROES.map((h, idx) => [h.id, idx] as const));
  for (const drop of encounter.tileDrops) {
    const heroIdx = HERO_INDEX.get(drop.heroId);
    if (heroIdx == null) continue;
    const suit = HEROES[heroIdx]!.suit;
    tokens.push({
      id: `drop-${drop.x}-${drop.y}-${drop.heroId}-${drop.dropId}`,
      kind: "drop",
      col: drop.x,
      row: drop.y,
      label: drop.dropId === "minion-part" ? "MP" : "BP",
      name: dropDisplayName(drop.dropId, suit),
      dropArt: dropArtFor(drop.dropId, suit),
      dropHeroId: drop.heroId,
    });
  }

  // Rebirth monster tokens (Ch4 Mistspawn / Infestation): count on the tile.
  for (const rt of encounter.rebirthTiles ?? []) {
    tokens.push({
      id: `rebirth-${rt.x}-${rt.y}`,
      kind: "rebirth",
      col: rt.x,
      row: rt.y,
      label: String(rt.tokens),
      name: `Rebirth: ${rt.tokens} monster token${rt.tokens === 1 ? "" : "s"}. After each hero turn with no kills, remove 1; at 0 an enemy that died here respawns with 50% health.`,
    });
  }

  // Memory Fragments — printed diamond glyphs on the drawn Spawn
  // Card, populated by `engine/encounter.ts > resolveSpawn` for
  // spawn-deck waves. Always empty for hand-authored Q1 waves.
  // Painted as a non-interactive icon on the tile; the actual
  // pickup credit (delver walks on, bumps `state.memoryChips`,
  // entry is spliced out) is deferred to a future slice.
  for (const mf of encounter.memoryFragments) {
    tokens.push({
      id: `memory-fragment-${mf.x}-${mf.y}`,
      kind: "memory-fragment",
      col: mf.x,
      row: mf.y,
      label: "MF",
      name: "Memory Chip",
    });
  }

  // Friendly Encounter tokens (Spawn Cards #13, #14). Sized to
  // match the Memory Fragment token; label "Friendly Encounter"
  // appears inside the chip. Pickup wiring lives in
  // `engine/movement.ts > moveDelverStep` and
  // `engine/witness.ts > stepWitness` -- the token is removed
  // when a mover lands on the tile and a Friendly Encounter
  // card is queued for resolution.
  for (const fe of encounter.friendlyEncounters ?? []) {
    tokens.push({
      id: `friendly-encounter-${fe.x}-${fe.y}`,
      kind: "friendly-encounter",
      col: fe.x,
      row: fe.y,
      label: "FE",
      name: "Friendly Encounter",
    });
  }

  return tokens;
}

/**
 * Resolve a dropId + delver suit to the per-suit/per-level token art
 * under `/tokens/`. Mirrors `screens/CampaignSheet.ts > partIcon`.
 *
 *   minion-part        → `/tokens/minion-{suit}.webp`
 *   boss-part-lvl-N    → `/tokens/boss-lvl-N-{suit}.webp`
 *   boss-part (bare)   → `/tokens/boss-lvl-1-{suit}.webp` (defaults to
 *                        the lvl-1 art since no level info was provided
 *                        — only Q1's lvl-1 art ships today anyway)
 */
function dropArtFor(dropId: string, suit: "mind" | "body"): string {
  if (dropId === "minion-part") return `/tokens/minion-${suit}.webp`;
  const m = dropId.match(/^boss-part-lvl-(\d+)$/);
  if (m) return `/tokens/boss-lvl-${m[1]}-${suit}.webp`;
  if (dropId === "boss-part") return `/tokens/boss-lvl-1-${suit}.webp`;
  return `/tokens/minion-${suit}.webp`;
}

function dropDisplayName(dropId: string, suit: "mind" | "body"): string {
  const suitLabel = suit === "mind" ? "Mind" : "Body";
  if (dropId === "minion-part") return `${suitLabel} Delver minion part`;
  const m = dropId.match(/^boss-part-lvl-(\d+)$/);
  if (m) return `${suitLabel} Delver boss part (Lvl ${m[1]})`;
  if (dropId === "boss-part") return `${suitLabel} Delver boss part`;
  return `${suitLabel} Delver drop`;
}

/**
 * HTML for the red-heart current-HP overlay, stamped on top of the
 * printed max-HP widget in the top-right of every enemy card. Only
 * emitted when the enemy has taken damage (`currentHp < maxHp`); a
 * fresh enemy reads its HP from the card art directly.
 *
 * Position + size are tuned by eye against the printed card template
 * (the heart widget sits ~5% from the top + right edges, ~18% wide).
 * If the card art template ever changes, retune `.enemy-card-hp-overlay`
 * in `styles.css`.
 *
 * The overlay also surfaces a `0` while an enemy is dying but the
 * shared counter hasn't finished yet (DESIGN.md §5.4.2 — body lingers
 * for the counter prompt). Once `finalizeAttackSession` flips
 * `enemy.alive = false`, the token disappears entirely and the
 * overlay goes with it.
 *
 * Returns `""` for non-enemy tokens (no HP fields populated). Callers
 * can safely concatenate the result onto any tile's innerHTML.
 */
export function renderEnemyHpOverlayHtml(token: BoardToken): string {
  if (token.currentHp == null || token.maxHp == null) return "";
  if (token.currentHp >= token.maxHp) return "";
  const safeName = escapeHtml(token.name);
  return `
    <span class="enemy-card-hp-overlay" title="${safeName}: ${token.currentHp} / ${token.maxHp} HP" aria-label="${safeName} HP ${token.currentHp} of ${token.maxHp}">
      <svg class="enemy-card-hp-heart" viewBox="0 0 100 90" aria-hidden="true" focusable="false">
        <path d="M50,82 C30,65 5,50 5,28 C5,15 16,5 30,5 C40,5 47,12 50,20 C53,12 60,5 70,5 C84,5 95,15 95,28 C95,50 70,65 50,82 Z" />
        <g fill="none" stroke="#7a1010" stroke-linecap="round" stroke-linejoin="round" stroke-width="3.5">
          <polyline points="51,17 46,33 55,41 48,57 52,76" />
          <polyline points="46,33 39,44 36,52" />
          <polyline points="55,41 63,50 65,57" />
        </g>
      </svg>
      <span class="enemy-card-hp-number">${token.currentHp}</span>
    </span>
  `;
}

/**
 * Small lock-icon overlay painted on an enemy tile WHEN AND ONLY
 * WHEN that enemy is currently protected by the Fatal Flaw rule
 * (rulebook p16) AND is sitting on its final point of HP — i.e.
 * the very next damage tick would otherwise kill it, but the
 * Fatal Flaw clamp is the only thing keeping it alive.
 *
 * The double gate exists because Fatal Flaw protection itself
 * lasts the WHOLE wave for any lower-tier-alive enemy, but the
 * lock is only USEFUL to the player as a "wait, why won't this
 * die?" signal — and that confusion only arises at HP 1, the
 * point at which their next swing would normally finish the
 * enemy. Showing a lock on a full-HP Fatal Flaw enemy creates
 * needless clutter (the player isn't trying to kill it yet) and
 * teaches a misleading rule ("anyone with a lock can't take
 * damage" — wrong, they can lose HP all the way down to 1).
 *
 * The printed card art already shows the tier text ("FATAL
 * FLAW: 3") so we deliberately DON'T paint the tier number here;
 * the lock alone says "you can't kill this right now" without
 * duplicating data the card already prints.
 *
 * Returns `""` when:
 *   - the enemy has no Fatal Flaw,
 *   - the enemy has Fatal Flaw but isn't currently protected
 *     (lowest-tier living Q2 enemy), OR
 *   - the enemy IS protected but has more than 1 HP left.
 *
 * Sits inside the same rotation-aware `.board-tile` container as
 * the HP heart so any Slip-Strider rotation cascades automatically.
 */
export function renderFatalFlawLockHtml(_token: BoardToken): string {
  return "";
}

/** Small badges for monster tokens on an enemy card (Guards / Vicious /
 *  Accurate). Empty string when the enemy has none. */
export function renderEnemyStatusTokensHtml(token: BoardToken): string {
  if (!token.statusTokens || token.statusTokens.length === 0) return "";
  const badges = token.statusTokens.map((t) =>
    `<span class="enemy-status-token" title="${escapeHtml(t.title)}">${escapeHtml(t.label)}</span>`).join("");
  return `<span class="enemy-status-tokens">${badges}</span>`;
}

function escapeHtml(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

// --- Humanoid chip stacking (moved from BoardScreen 2026-11-15) ------------

/**
 * Per-token offset (as a % of the board width / height) from the cell
 * centre for a humanoid chip stacked on a tile with `total` other
 * humanoids (delvers + Witness companion). See the long comment in
 * `BoardScreen.ts > renderTokens` for the layout rationale; the table
 * below is the authoritative version. Shared by every screen that draws
 * the board (BoardScreen, DelverSpawnPick, WavePhases) so a fully
 * stacked spawn tile looks the same everywhere (the spawn-pick screen
 * used to fan 3 chips in a row past the tile edge until Start Wave).
 *
 *   total = 1: { dx: 0, dy: 0 }                       (centred)
 *   total = 2: idx 0 → (-fan, 0)                       (left)
 *              idx 1 → (+fan, 0)                       (right)
 *   total = 3: idx 0 → (-fan, -fan)                    (top-left)
 *              idx 1 → (+fan, -fan)                    (top-right)
 *              idx 2 → (   0, +fan)                    (bottom-centre)
 *   total ≥ 4: linear horizontal fan (defensive — only 3 humanoid
 *              kinds exist today so this branch is unreachable).
 *
 * `fan` = `CELL_SIZE_PCT * HUMANOID_FAN_PCT` (≈ a chip radius), so
 * top-row chips sit edge-to-edge horizontally AND the bottom-row chip
 * sits clear of the top row vertically — all three fit inside the
 * printed cell rim instead of spilling past the right edge of the
 * tile (the bug 2026-05-19 — see the screenshot in the chat history).
 */
export function humanoidStackOffset(idx: number, total: number): { dxPct: number; dyPct: number } {
  const fan = CELL_SIZE_PCT * HUMANOID_FAN_PCT;
  if (total <= 1) return { dxPct: 0, dyPct: 0 };
  if (total === 2) return { dxPct: (idx === 0 ? -1 : 1) * fan, dyPct: 0 };
  if (total === 3) {
    if (idx === 0) return { dxPct: -fan, dyPct: -fan };
    if (idx === 1) return { dxPct:  fan, dyPct: -fan };
    return { dxPct: 0, dyPct: fan }; // idx === 2 (Witness in canonical order)
  }
  // 4+ humanoid mates — extremely defensive (no such scenario today);
  // fall through to a linear horizontal fan so the chips at least
  // don't end up on top of each other if a future feature lands a
  // 4th humanoid kind.
  return {
    dxPct: (idx - (total - 1) / 2) * (CELL_SIZE_PCT * 0.35),
    dyPct: 0,
  };
}

/** Per-axis humanoid chip offset from the cell centre, as a multiple
 *  of `CELL_SIZE_PCT`. ≈ half a chip diameter so two stacked chips
 *  sit edge-to-edge with no overlap on the row that owns them. */
const HUMANOID_FAN_PCT = 0.175;
